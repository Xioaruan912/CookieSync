export const commonSites = Object.entries(commonSiteGroups).flatMap(([category, text]) =>
  text.split(' ').map(entry => {
    const [name, domain] = entry.split('|');
    return { name: name.replaceAll('_', ' '), domain, category };
  }),
);

export type SiteRule = { enabled: boolean; updatedAt: number; revision: string };
export type SiteRules = Record<string, SiteRule>;
export const siteRulePrefix = 'cookiesync-site-rule-v1:';
export function siteRulesFromStorage(data: Record<string, unknown>): SiteRules {
  return mergeSiteRules(
    Object.fromEntries(
      Object.entries(data)
        .filter(([key]) => key.startsWith(siteRulePrefix))
        .map(([key, value]) => [key.slice(siteRulePrefix.length), value]),
    ) as SiteRules,
  );
}

export function normalizeSiteDomain(input: string): string {
  const raw = input.trim();
  if (!raw || /[\s*@\\]/.test(raw)) throw new Error('请输入有效网站域名，例如 nodeseek.com');
  let url: URL;
  try {
    url = new URL(raw.includes('://') ? raw : `https://${raw}`);
  } catch {
    throw new Error('请输入有效网站域名');
  }
  const domain = url.hostname.toLowerCase().replace(/^www\./, '');
  if (
    !['http:', 'https:'].includes(url.protocol) ||
    url.username ||
    url.password ||
    url.port ||
    domain.length > 253 ||
    !domain.includes('.') ||
    !domain.split('.').every(part => /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(part)) ||
    /^\d+(?:\.\d+){3}$/.test(domain) ||
    ['com.cn', 'net.cn', 'org.cn', 'gov.cn', 'edu.cn', 'co.uk', 'com.hk', 'com.tw'].includes(domain)
  )
    throw new Error('请输入具体网站域名，不能使用 IP、端口或公共后缀');
  return domain;
}

export function validSiteRule(value: unknown): value is SiteRule {
  const rule = value as SiteRule;
  return (
    !!rule &&
    typeof rule.enabled === 'boolean' &&
    Number.isSafeInteger(rule.updatedAt) &&
    rule.updatedAt > 0 &&
    typeof rule.revision === 'string' &&
    rule.revision.length > 0 &&
    rule.revision.length <= 80
  );
}

export function mergeSiteRules(...sources: SiteRules[]): SiteRules {
  const result: SiteRules = {};
  for (const source of sources)
    for (const [domain, rule] of Object.entries(source)) {
      if (!validSiteRule(rule)) throw new Error('网站名单配置格式错误');
      if (normalizeSiteDomain(domain) !== domain) throw new Error('网站名单包含无效域名');
      const old = result[domain];
      if (
        !old ||
        rule.updatedAt > old.updatedAt ||
        (rule.updatedAt === old.updatedAt &&
          (rule.revision > old.revision || (rule.revision === old.revision && !rule.enabled)))
      )
        result[domain] = rule;
    }
  return Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
}

export function isSiteAllowed(host: string, rules: SiteRules = {}): boolean {
  let domain: string;
  try {
    domain = new URL(`https://${host}`).hostname.toLowerCase().replace(/^www\./, '');
  } catch {
    return false;
  }
  const candidates = new Map(commonSites.map(site => [site.domain, true]));
  for (const [name, rule] of Object.entries(rules)) candidates.set(name, rule.enabled);
  const match = [...candidates.keys()]
    .filter(name => domain === name || domain.endsWith(`.${name}`))
    .sort((a, b) => b.length - a.length)[0];
  return match !== undefined && candidates.get(match) === true;
}

export function isAutomaticCookieAllowed(
  cookie: { domain?: string | null; hostOnly?: boolean | null },
  host: string,
  rules: SiteRules,
): boolean {
  const domain = cookie.domain?.toLowerCase().replace(/^\./, '') || host;
  if (isSiteAllowed(domain, rules)) return true;
  // An allowed subdomain may depend on a shared parent-domain login Cookie even when the parent is not listed.
  // Explicit parent opt-outs remain binding; unrelated child cookies never gain permission this way.
  const page = new URL(`https://${host}`).hostname.toLowerCase();
  if (cookie.hostOnly || !page.endsWith(`.${domain}`) || !isSiteAllowed(host, rules)) return false;
  const explicit = Object.keys(rules)
    .filter(name => domain === name || domain.endsWith(`.${name}`))
    .sort((a, b) => b.length - a.length)[0];
  return explicit === undefined || rules[explicit].enabled;
}
